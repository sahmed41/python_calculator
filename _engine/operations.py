def add(num1, num2):
    """
    This function adds num1 and num2, and returns the total
    """
    return num1 + num2

def subtract(num1, num2):
    """
    This function sumbstracts num2 from num1, and returns the total
    """
    return num1 - num2

def multiply(num1, num2):
    """
    This function multiplies num1 and num2, and returns the total
    """
    return num1 * num2

def divide(num1, num2):
    """
    This function divides num1 by num2, and returns the total
    """
    return num1 / num2